import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const target = path.join(root, 'appscript.txt');
const marker = '// BEGIN GENERATED PHASE 1 COMPATIBILITY';
const current = fs.readFileSync(target, 'utf8');
const legacy = current.split(marker)[0].trimEnd();
const core = fs.readFileSync(path.join(root, 'src/features/roster/compatibility.js'), 'utf8').replace(/^export default RosterCompatibility;\s*$/m, '').trimEnd();
if (/^export /m.test(core)) throw new Error('Unexpected exports in shared Apps Script source');
const io = fs.readFileSync(path.join(root, 'backend/roster-v2.gs'), 'utf8').trimEnd();
const protocol = fs.readFileSync(path.join(root, 'src/features/roster/queue/protocol.js'), 'utf8').replace(/^import .*;\r?$/m, '').replace(/^export default DraftProtocol;\s*$/m, '').trim();
const draft = fs.readFileSync(path.join(root, 'backend/roster-draft.gs'), 'utf8').trim();
const generated = `${legacy}\n\n${marker}\n// Generated by npm run build:appscript. Edit the shared module or backend/roster-v2.gs.\n${core}\n\n${io}\n\n${protocol}\n\n${draft}\n// END GENERATED PHASE 1 COMPATIBILITY\n`;
if (process.argv.includes('--check')) {
  if (current.replaceAll('\r\n', '\n') !== generated.replaceAll('\r\n', '\n')) throw new Error('appscript.txt shared bundle is stale; run npm run build:appscript');
  console.log('Apps Script bundle matches shared frontend contract and backend adapter.');
} else {
  fs.writeFileSync(target, generated);
  console.log('Generated local appscript.txt; nothing deployed.');
}
